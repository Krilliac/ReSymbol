fn java_string_literal(value: &str) -> String {
    let mut output = String::with_capacity(value.len().saturating_add(2));
    output.push('"');
    for character in value.chars() {
        match character {
            '"' => output.push_str("\\\""),
            '\\' => output.push_str("\\\\"),
            '\n' => output.push_str("\\n"),
            '\r' => output.push_str("\\r"),
            '\t' => output.push_str("\\t"),
            '\u{08}' => output.push_str("\\b"),
            '\u{0c}' => output.push_str("\\f"),
            ' '..='~' => output.push(character),
            value if u32::from(value) <= 0xff => {
                write!(output, "\\{:03o}", u32::from(value))
                    .expect("writing to a String cannot fail");
            }
            value => {
                let mut units = [0_u16; 2];
                for unit in value.encode_utf16(&mut units) {
                    write!(output, "\\u{unit:04x}").expect("writing to a String cannot fail");
                }
            }
        }
    }
    output.push('"');
    output
}

fn base64_encode(bytes: &[u8]) -> String {
    const ALPHABET: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut output = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let first = chunk[0];
        let second = chunk.get(1).copied().unwrap_or(0);
        let third = chunk.get(2).copied().unwrap_or(0);
        output.push(char::from(ALPHABET[usize::from(first >> 2)]));
        output.push(char::from(
            ALPHABET[usize::from(((first & 0x03) << 4) | (second >> 4))],
        ));
        if chunk.len() >= 2 {
            output.push(char::from(
                ALPHABET[usize::from(((second & 0x0f) << 2) | (third >> 6))],
            ));
        } else {
            output.push('=');
        }
        if chunk.len() == 3 {
            output.push(char::from(ALPHABET[usize::from(third & 0x3f)]));
        } else {
            output.push('=');
        }
    }
    output
}

fn push_checked(output: &mut String, value: &str) -> Result<(), GhidraJavaError> {
    if output
        .len()
        .checked_add(value.len())
        .is_none_or(|length| length > MAX_SCRIPT_BYTES)
    {
        return Err(GhidraJavaError::OutputLimitExceeded {
            limit: MAX_SCRIPT_BYTES,
        });
    }
    output.push_str(value);
    Ok(())
}

