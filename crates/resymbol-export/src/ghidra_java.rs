use std::fmt::Write as _;

use thiserror::Error;

use crate::{ExportFunction, ExportProjection, ProjectionValidationError};

const MAX_SCRIPT_BYTES: usize = 32 * 1024 * 1024;
const RECORDS_PER_METHOD: usize = 256;
// Java class files encode each string constant with a u16 byte length. Keep
// generated record-data constants comfortably below that hard limit while
// packing many records into each constant-pool entry.
const MAX_RECORD_DATA_LITERAL_BYTES: usize = 48 * 1024;
const MAX_CLASS_NAME_BYTES: usize = 128;

/// Failure to render a built-in Ghidra Java script.
#[derive(Debug, Error, PartialEq, Eq)]
#[non_exhaustive]
pub enum GhidraJavaError {
    #[error("the export projection is invalid: {0}")]
    InvalidProjection(#[from] ProjectionValidationError),
    #[error("`{name}` is not a conservative Java class name")]
    InvalidClassName { name: String },
    #[error("the generated Ghidra Java script exceeds {limit} bytes")]
    OutputLimitExceeded { limit: usize },
}

#[derive(Debug)]
enum Record {
    Function(String),
    Global(String),
}

/// Render a deterministic Ghidra Java script with the supplied public class.
///
/// Ghidra requires the source filename to match this class name. The accepted
/// subset is deliberately conservative and excludes keywords, Unicode
/// confusables, path separators, and package syntax.
pub fn render_ghidra_java(
    projection: &ExportProjection,
    class_name: &str,
) -> Result<String, GhidraJavaError> {
    projection.validate()?;
    validate_ghidra_java_class_name(class_name)?;

    let records = collect_records(projection);
    let batch_count = records.len().div_ceil(RECORDS_PER_METHOD);
    let mut output = String::new();
    push_checked(
        &mut output,
        "// Generated by ReSymbol. Review before running.\n\
//@category ReSymbol\n\n\
import java.math.BigInteger;\n\
import java.nio.charset.StandardCharsets;\n\
import java.util.Base64;\n\n\
import ghidra.app.script.GhidraScript;\n\
import ghidra.program.model.address.Address;\n\
import ghidra.program.model.address.AddressSet;\n\
import ghidra.program.model.listing.Function;\n\
import ghidra.program.model.listing.FunctionManager;\n\
import ghidra.program.model.mem.Memory;\n\
import ghidra.program.model.symbol.SourceType;\n\
import ghidra.program.model.symbol.Symbol;\n\
import ghidra.program.model.symbol.SymbolTable;\n\n",
    )?;
    push_checked(
        &mut output,
        &format!("public class {class_name} extends GhidraScript {{\n"),
    )?;
    push_checked(
        &mut output,
        &format!(
            "    private static final String EXPECTED_SHA256 = {};\n",
            java_string_literal(projection.binary.id.as_str())
        ),
    )?;
    push_checked(
        &mut output,
        r#"
    private Address imageBase;
    private Memory memory;
    private FunctionManager functionManager;
    private SymbolTable symbolTable;

    @Override
    protected void run() throws Exception {
        // This check intentionally precedes every program mutation.
        verifyIdentity();
        imageBase = currentProgram.getImageBase();
        memory = currentProgram.getMemory();
        functionManager = currentProgram.getFunctionManager();
        symbolTable = currentProgram.getSymbolTable();
"#,
    )?;
    for batch in 0..batch_count {
        push_checked(&mut output, &format!("        applyBatch{batch}();\n"))?;
    }
    push_checked(
        &mut output,
        r#"        println("[ReSymbol] import complete");
    }

    private void verifyIdentity() {
        String actual = currentProgram.getExecutableSHA256();
        if (actual == null || !EXPECTED_SHA256.equalsIgnoreCase(actual)) {
            throw new IllegalStateException(
                "loaded program SHA-256 does not match this ReSymbol export"
            );
        }
    }

    private Address toAddress(BigInteger rva) throws Exception {
        if (rva.signum() < 0) {
            throw new IllegalArgumentException("negative RVA");
        }
        Address address = imageBase.addNoWrap(rva);
        if (!memory.contains(address)) {
            throw new IllegalArgumentException("resolved address is not mapped");
        }
        return address;
    }

    private boolean hasProtectedName(Address address) {
        for (Symbol symbol : symbolTable.getSymbols(address)) {
            SourceType source = symbol.getSource();
            if (source != SourceType.DEFAULT && source != SourceType.ANALYSIS) {
                return true;
            }
        }
        return false;
    }

    private boolean createKnownFunction(Address start, BigInteger size)
            throws Exception {
        if (size == null || size.signum() <= 0) {
            return false;
        }
        Address end = start.addNoWrap(size.subtract(BigInteger.ONE));
        if (!memory.contains(start, end)) {
            throw new IllegalArgumentException("function range is not wholly mapped");
        }
        if (functionManager.getFunctionAt(start) != null) {
            return true; // Never replace an existing function body.
        }
        if (functionManager.getFunctionContaining(start) != null) {
            throw new IllegalArgumentException(
                "function start lies inside an existing function"
            );
        }
        if (hasProtectedName(start)) {
            throw new IllegalStateException(
                "function start has a protected existing name"
            );
        }
        AddressSet body = new AddressSet(start, end); // End is inclusive in Ghidra.
        Function created = functionManager.createFunction(
            null, start, body, SourceType.ANALYSIS
        );
        if (created == null) {
            throw new IllegalStateException("Ghidra rejected an overlapping function body");
        }
        return true;
    }

    private void applyName(Address address, String name) throws Exception {
        if (name == null || hasProtectedName(address)) {
            return;
        }
        Function function = functionManager.getFunctionAt(address);
        if (function != null) {
            function.setName(name, SourceType.ANALYSIS);
        }
        else {
            createLabel(address, name, true, SourceType.ANALYSIS);
        }
    }

    private static String decodeName(String encoded) {
        return new String(
            Base64.getDecoder().decode(encoded), StandardCharsets.UTF_8
        );
    }

    private void report(String kind, String rva, Exception error) {
        printerr(
            "[ReSymbol] " + kind + " failed at RVA 0x" + rva + ": "
                + error.getClass().getSimpleName()
        );
    }

    private void applyRecordBatch(String records) {
        int start = 0;
        while (start < records.length()) {
            int end = records.indexOf('\n', start);
            if (end < 0) {
                end = records.length();
            }
            String record = records.substring(start, end);
            if (record.length() < 3 || record.charAt(1) != ',') {
                printerr("[ReSymbol] invalid generated record envelope");
            }
            else if (record.charAt(0) == 'F') {
                applyFunctionRecord(record.substring(2));
            }
            else if (record.charAt(0) == 'G') {
                applyGlobalRecord(record.substring(2));
            }
            else {
                printerr("[ReSymbol] invalid generated record kind");
            }
            start = end + 1;
        }
    }

    private void applyFunctionRecord(String record) {
        String[] fields = record.split(",", -1);
        if (fields.length != 3) {
            printerr("[ReSymbol] invalid generated function record");
            return;
        }

        BigInteger rva;
        BigInteger size;
        String name;
        Address start;
        try {
            rva = new BigInteger(fields[0], 16);
            size = fields[1].isEmpty() ? null : new BigInteger(fields[1], 16);
            name = fields[2].isEmpty() ? null : decodeName(fields[2]);
            start = toAddress(rva);
        }
        catch (Exception error) {
            report("function address", fields[0], error);
            return;
        }

        boolean functionReady = false;
        if (size != null) {
            try {
                functionReady = createKnownFunction(start, size);
            }
            catch (Exception error) {
                report("function range", fields[0], error);
            }
        }
        else {
            try {
                Function exact = functionManager.getFunctionAt(start);
                if (exact == null) {
                    if (functionManager.getFunctionContaining(start) != null) {
                        throw new IllegalArgumentException(
                            "function start lies inside an existing function"
                        );
                    }
                    throw new IllegalArgumentException(
                        "name-only claim has no function at the exact start"
                    );
                }
                functionReady = true;
            }
            catch (Exception error) {
                report("function identity", fields[0], error);
            }
        }
        if (functionReady) {
            try {
                applyName(start, name);
            }
            catch (Exception error) {
                report("function name", fields[0], error);
            }
        }
    }

    private void applyGlobalRecord(String record) {
        String[] fields = record.split(",", -1);
        if (fields.length != 2) {
            printerr("[ReSymbol] invalid generated global record");
            return;
        }
        try {
            BigInteger rva = new BigInteger(fields[0], 16);
            Address address = toAddress(rva);
            if (functionManager.getFunctionContaining(address) != null) {
                throw new IllegalArgumentException(
                    "global address lies in an existing function"
                );
            }
            applyName(address, decodeName(fields[1]));
        }
        catch (Exception error) {
            report("global name", fields[0], error);
        }
    }

"#,
    )?;

    for (batch, records) in records.chunks(RECORDS_PER_METHOD).enumerate() {
        let data = record_batch_data(records);
        push_checked(
            &mut output,
            &format!("    private void applyBatch{batch}() {{\n"),
        )?;
        push_checked(
            &mut output,
            &format!(
                "        StringBuilder records = new StringBuilder({});\n",
                data.len()
            ),
        )?;
        // The record envelope is ASCII-only, so byte slicing cannot split a
        // UTF-8 code point. StringBuilder prevents javac from folding adjacent
        // literals back into one oversized class-file string constant.
        for chunk_start in (0..data.len()).step_by(MAX_RECORD_DATA_LITERAL_BYTES) {
            let chunk_end = data
                .len()
                .min(chunk_start.saturating_add(MAX_RECORD_DATA_LITERAL_BYTES));
            push_checked(
                &mut output,
                &format!(
                    "        records.append({});\n",
                    java_string_literal(&data[chunk_start..chunk_end])
                ),
            )?;
        }
        push_checked(
            &mut output,
            "        applyRecordBatch(records.toString());\n",
        )?;
        push_checked(&mut output, "    }\n\n")?;
    }
    push_checked(&mut output, "}\n")?;

    Ok(output)
}

fn collect_records(projection: &ExportProjection) -> Vec<Record> {
    let accepted_sizes = non_overlapping_sizes(&projection.functions);
    let mut records = Vec::new();
    for (function, size) in projection.functions.iter().zip(&accepted_sizes) {
        if !emits_function_record(function, *size) {
            continue;
        }
        let size = size.map_or_else(String::new, |value| format!("{value:x}"));
        let name = function
            .selected_name
            .as_ref()
            .map_or_else(String::new, |value| {
                base64_encode(value.output_name.as_bytes())
            });
        records.push(Record::Function(format!(
            "{:x},{size},{name}",
            function.rva
        )));
    }
    for global in &projection.globals {
        let Some(name) = &global.selected_name else {
            continue;
        };
        if projection
            .functions
            .binary_search_by_key(&global.rva, |function| function.rva)
            .is_ok_and(|index| {
                emits_function_record(&projection.functions[index], accepted_sizes[index])
            })
        {
            continue;
        }
        records.push(Record::Global(format!(
            "{:x},{}",
            global.rva,
            base64_encode(name.output_name.as_bytes())
        )));
    }
    records
}

fn emits_function_record(function: &ExportFunction, accepted_size: Option<u64>) -> bool {
    function.selected_name.is_some() || accepted_size.is_some()
}

fn record_batch_data(records: &[Record]) -> String {
    let capacity = records
        .iter()
        .map(|record| match record {
            Record::Function(value) | Record::Global(value) => value.len().saturating_add(3),
        })
        .fold(0_usize, usize::saturating_add);
    let mut data = String::with_capacity(capacity);
    for record in records {
        let (kind, value) = match record {
            Record::Function(value) => ('F', value),
            Record::Global(value) => ('G', value),
        };
        data.push(kind);
        data.push(',');
        data.push_str(value);
        data.push('\n');
    }
    debug_assert!(data.is_ascii());
    data
}

fn non_overlapping_sizes(functions: &[ExportFunction]) -> Vec<Option<u64>> {
    let mut accepted = functions.iter().map(|value| value.size).collect::<Vec<_>>();
    let mut ranges = functions
        .iter()
        .enumerate()
        .filter_map(|(index, value)| {
            let size = value.size?;
            Some((index, value.rva, value.rva.checked_add(size)?))
        })
        .collect::<Vec<_>>();
    ranges.sort_by_key(|value| (value.1, value.2, value.0));

    let mut cluster_start = 0;
    while cluster_start < ranges.len() {
        let mut cluster_end = ranges[cluster_start].2;
        let mut next = cluster_start + 1;
        while next < ranges.len() && ranges[next].1 < cluster_end {
            cluster_end = cluster_end.max(ranges[next].2);
            next += 1;
        }
        if next - cluster_start > 1 {
            for value in &ranges[cluster_start..next] {
                accepted[value.0] = None;
            }
        }
        cluster_start = next;
    }
    accepted
}

/// Validate the conservative Java identifier subset accepted for Ghidra scripts.
pub fn validate_ghidra_java_class_name(class_name: &str) -> Result<(), GhidraJavaError> {
    let valid_length = !class_name.is_empty() && class_name.len() <= MAX_CLASS_NAME_BYTES;
    let mut bytes = class_name.bytes();
    let valid_start = bytes
        .next()
        .is_some_and(|value| value.is_ascii_alphabetic() || matches!(value, b'_' | b'$'));
    let valid_rest =
        bytes.all(|value| value.is_ascii_alphanumeric() || matches!(value, b'_' | b'$'));
    if valid_length && valid_start && valid_rest && !is_java_keyword(class_name) {
        Ok(())
    } else {
        Err(GhidraJavaError::InvalidClassName {
            name: class_name.to_owned(),
        })
    }
}

